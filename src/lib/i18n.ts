interface I18nStore {
  lang: Lang;
  setLang: (l: Lang) => void;
}

export const useI18nStore = create<I18nStore>()(
  persist((set) => ({ lang: "en", setLang: (lang) => set({ lang }) }), { name: "ephemera-lang" }),
);

export function useT() {
  const lang = useI18nStore((s) => s.lang);
  return dict[lang];
}
